# --- Range weighting --------------------------------------------------------------
#
# The composite's grid is a rectangle; the radars' sight is not. A beam climbs and
# widens with range, so the far corners of the domain are measured from above the
# weather. These tests pin the consequence: `chmi` is the one source whose consensus
# weight depends on where the user lives.


@pytest.mark.parametrize(
    ("name", "latitude", "longitude", "expected_km"),
    [
        ("Brno", 49.1951, 16.6068, 37),
        ("Praha", 50.0755, 14.4378, 64),
        ("Ostrava", 49.8209, 18.2625, 112),
        ("Bielsko-Biala", 49.8224, 19.0584, 167),
    ],
)
def test_distance_to_the_nearest_czrad_radar(
    name: str, latitude: float, longitude: float, expected_km: int
) -> None:
    """Skalky (49.501 N, 16.790 E) and Brdy-Praha (49.658 N, 13.818 E), per chmi.cz."""
    assert nearest_radar_km(latitude, longitude) == pytest.approx(expected_km, abs=2), name


def test_close_in_locations_keep_the_full_weight() -> None:
    """Inside 120 km the beam is still under ~2.7 km — nothing to discount."""
    assert range_factor(49.1951, 16.6068) == 1.0  # Brno, 37 km
    assert range_factor(49.8209, 18.2625) == 1.0  # Ostrava, 112 km


def test_the_weight_decays_beyond_the_full_range_and_then_floors() -> None:
    """Linear from 1.0 at `RANGE_FULL_KM` to `RANGE_MIN_FACTOR` at `RANGE_LIMIT_KM`."""
    midpoint = (RANGE_FULL_KM + RANGE_LIMIT_KM) / 2
    factors = [
        range_factor(*_at_range_from_skalky(km))
        for km in (RANGE_FULL_KM, midpoint, RANGE_LIMIT_KM, RANGE_LIMIT_KM + 50)
    ]

    assert factors[0] == pytest.approx(1.0, abs=0.02)
    assert factors[1] == pytest.approx((1.0 + RANGE_MIN_FACTOR) / 2, abs=0.02)
    assert factors[2] == pytest.approx(RANGE_MIN_FACTOR, abs=0.02)
    assert factors[3] == RANGE_MIN_FACTOR  # floored, never zero


def _at_range_from_skalky(km: float) -> tuple[float, float]:
    """A point due east of Skalky at roughly `km` — enough to exercise the curve."""
    skalky_lat, skalky_lon = 49.501, 16.790
    deg = km / (111.320 * math.cos(math.radians(skalky_lat)))
    return skalky_lat, skalky_lon + deg


def test_bielsko_biala_is_weighted_down_but_still_votes() -> None:
    """The case this was built for, stated as a number.

    Bielsko-Biala is 167 km from Skalky, where the 0.5 deg beam centre is ~3.9 km up,
    while the Polish radar feeding OPERA stands 44 km away and looks at ~0.85 km. So
    `chmi` must weigh less than `librewxr` there by a clear margin — enough that when
    the two disagree about rain, the better-sighted one wins the slot.
    """
    weight = reliability_at(*_BIELSKO)

    assert weight == pytest.approx(0.67, abs=0.02)
    assert weight < RELIABILITY[SOURCE_CHMI]
    assert weight < RELIABILITY["librewxr"]
    # The decisive property: librewxr voting wet outweighs chmi voting dry.
    assert RELIABILITY["librewxr"] / (RELIABILITY["librewxr"] + weight) > 0.5


def test_the_weight_never_exceeds_the_static_one() -> None:
    """The range factor only ever discounts; it cannot promote the source."""
    for latitude, longitude in (
        _BIELSKO,
        (49.501, 16.790),  # standing on Skalky itself
        (49.1951, 16.6068),
        (48.35, 19.32),  # the far south-eastern corner of the box
    ):
        assert reliability_at(latitude, longitude) <= RELIABILITY[SOURCE_CHMI]
        assert reliability_at(latitude, longitude) > 0.0


