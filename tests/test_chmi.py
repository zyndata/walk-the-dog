def test_the_recorded_frame_is_entirely_on_the_published_palette() -> None:
    """Every opaque pixel of a real frame is an exact palette colour or the outline.

    If CHMI ever changes how these are rendered, this is the test that says so
    instead of the readings quietly drifting.
    """
    with Image.open(io.BytesIO(load_bytes("chmi", "observed.png"))) as image:
        rgba = np.asarray(image.convert("RGBA"))

    known = {*PALETTE_RGB, DOMAIN_OUTLINE_RGB}
    opaque = rgba[rgba[..., 3] > 0][:, :3]
    unknown = {tuple(px) for px in opaque.tolist()} - known

    assert not unknown, f"unrecognised colours in a real frame: {sorted(unknown)}"


def test_the_recorded_forecast_archive_holds_six_ten_minute_frames() -> None:
    """`ft60s10` on the tin, and the same on the inside."""
    with tarfile.open(fileobj=io.BytesIO(load_bytes("chmi", "forecast.tar"))) as archive:
        frames = [m for m in archive.getmembers() if m.isfile() and m.name.endswith(".png")]
        sizes = set()
        for member in frames:
            payload = archive.extractfile(member)
            assert payload is not None
            with Image.open(io.BytesIO(payload.read())) as image:
                sizes.add((image.width, image.height))

    assert len(frames) == FORECAST_FRAMES
    assert sizes == {(FRAME_WIDTH, FRAME_HEIGHT)}


