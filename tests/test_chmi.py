async def test_a_failure_reuses_the_previous_frames_while_they_are_fresh(
    hass: HomeAssistant,
    aioclient_mock: AiohttpClientMocker,
    chmi_geometry: SampleGeometry,
    at_run: datetime,
) -> None:
    """One bad cycle should not blind the source; a stale one still must."""
    _mock_run(aioclient_mock)
    adapter = ChmiAdapter(UA)
    session = async_get_clientsession(hass)
    await adapter.fetch(session, chmi_geometry, at_run)

