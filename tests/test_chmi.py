# --- Projection -------------------------------------------------------------------


def test_the_published_extent_describes_a_web_mercator_frame() -> None:
    """Longitude and Mercator northing must share one scale, or it is not EPSG:3857.

    Deriving `px per radian of longitude` and `px per Mercator unit` from CHMI's
    published image extent and the real 680x460 frame gives the same number to
    0.02 %. No other projection would come out consistent.
    """
    px_per_lon_radian = FRAME_WIDTH / math.radians(IMAGE_EAST_LON - IMAGE_WEST_LON)
    merc_span = math.asinh(math.tan(math.radians(IMAGE_NORTH_LAT))) - math.asinh(
        math.tan(math.radians(IMAGE_SOUTH_LAT))
    )
    px_per_merc_unit = FRAME_HEIGHT / merc_span

    assert px_per_lon_radian == pytest.approx(px_per_merc_unit, rel=1e-3)


def test_the_data_rectangle_lands_where_chmi_says_it_does() -> None:
    """The data extent maps to (0, 82)-(598, 460) inside the 680x460 image.

    This is the independent check on the whole geometry: CHMI publishes the image
    extent and the data extent separately, and the second falls on whole-pixel
    boundaries only if the first is being applied correctly.
    """
    x0, y0 = to_pixel(DATA_NORTH_LAT, DATA_WEST_LON)
    x1, y1 = to_pixel(DATA_SOUTH_LAT, DATA_EAST_LON)

    assert (x0, y1) == pytest.approx((0.0, FRAME_HEIGHT), abs=0.1)
    assert y0 == pytest.approx(82.0, abs=0.1)
    assert x1 == pytest.approx(598.0, abs=0.1)


def test_one_pixel_is_about_one_kilometre() -> None:
    """CHMI states 1x1 km; the frame's own extent has to agree."""
    mid_lat = (DATA_NORTH_LAT + DATA_SOUTH_LAT) / 2
    km_per_deg_lon = 111.320 * math.cos(math.radians(mid_lat))
    km_per_px = km_per_deg_lon * (IMAGE_EAST_LON - IMAGE_WEST_LON) / FRAME_WIDTH

    assert km_per_px == pytest.approx(1.0, abs=0.02)


def test_the_frame_window_lands_on_bielsko_biala() -> None:
    """~557, 267 in frame pixels — inside the data rectangle, near its eastern edge."""
    window = frame_window(CHMI_GEOMETRY)

    assert window.x0 <= 557 <= window.x1
    assert window.y0 <= 267 <= window.y1
    assert window.box == (window.x0, window.y0, window.x1, window.y1)


def test_a_five_kilometre_disc_is_about_ten_pixels_across() -> None:
    """~1 km per pixel: the disc is small, which is why only it is decoded."""
    window = frame_window(CHMI_GEOMETRY)

    assert 8 <= window.x1 - window.x0 <= 14
    assert 8 <= window.y1 - window.y0 <= 14
    assert 60 <= int(window.mask.sum()) <= 100


